"""PA1 RIPPER evaluation and the shared mRMR-inspired selector.

No data or fitted state is loaded at import. Callers supply raw predictors,
target, outer CV and the unfitted filter preprocessor explicitly.
"""
import json
from pathlib import Path
import numpy as np
import pandas as pd
from scipy import sparse
from sklearn.base import BaseEstimator, TransformerMixin, clone
from sklearn.feature_selection import SelectKBest, f_classif, mutual_info_classif
from sklearn.model_selection import StratifiedKFold
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
                             f1_score, balanced_accuracy_score)
from wittgenstein import RIPPER

N_SELECTED_FEATURES = 15
N_WRAPPER_FEATURES = 3
inner_cv = StratifiedKFold(n_splits=2, shuffle=True, random_state=42)

def prepare_predictors(X):
    """
    Preserve numerical values and convert nominal columns to object strings.
    """

    X_prepared = X.copy()

    for feature in X_prepared.select_dtypes(exclude=np.number):
        X_prepared[feature] = (
            X_prepared[feature]
            .astype(str)
            .astype(object)
        )

    return X_prepared

def create_classifier():
    return RIPPER(random_state=42)

def fit_predict(X_train, y_train, X_valid):
    """
    Fit RIPPER using training data and predict the validation observations.
    """

    classifier = create_classifier()

    classifier.fit(
        prepare_predictors(X_train).reset_index(drop=True),
        y=y_train.to_numpy(),
        pos_class=1
    )

    predictions = classifier.predict(
        prepare_predictors(X_valid).reset_index(drop=True)
    )

    return np.asarray(predictions, dtype=int), classifier

class MRMRSelector(BaseEstimator, TransformerMixin):
    """
    Greedy multivariate filter inspired by mRMR.

    Features are selected by maximizing target relevance while
    penalizing redundancy with features already selected.
    """

    def __init__(
        self,
        k=15,
        random_state=42
    ):
        self.k = k
        self.random_state = random_state

    def fit(self, X, y):

        # Convert sparse matrices generated by one-hot encoding to dense arrays.
        if sparse.issparse(X):
            X_array = X.toarray()
        else:
            X_array = np.asarray(X)

        n_features = X_array.shape[1]

        if self.k > n_features:
            raise ValueError(
                "k cannot be greater than the number of features."
            )

        # Measure the relevance of every feature with respect to the target.
        relevance = mutual_info_classif(
            X_array,
            y,
            random_state=self.random_state
        )

        # Correlation matrix used to quantify redundancy.
        correlation = np.corrcoef(
            X_array,
            rowvar=False
        )

        correlation = np.nan_to_num(
            np.abs(correlation),
            nan=0.0
        )

        selected = []

        # Start with the most relevant feature.
        first_feature = int(np.argmax(relevance))
        selected.append(first_feature)

        # Greedily add features with high relevance and low redundancy.
        while len(selected) < self.k:

            best_feature = None
            best_score = -np.inf

            for feature in range(n_features):

                if feature in selected:
                    continue

                redundancy = np.mean(
                    correlation[feature, selected]
                )

                score = (
                    relevance[feature]
                    - redundancy
                )

                if score > best_score:
                    best_score = score
                    best_feature = feature

            selected.append(best_feature)

        self.selected_indices_ = np.array(selected)
        self.relevance_scores_ = relevance

        return self

    def transform(self, X):

        return X[:, self.selected_indices_]

    def get_support(self):

        return self.selected_indices_

def restore_numerical_features(X_transformed, X_original, feature_names):
    """
    Restore numerical units while retaining selected dummy indicators.
    """

    X_selected = pd.DataFrame(
        X_transformed,
        columns=feature_names,
        index=X_original.index
    )

    for feature in feature_names:

        if feature.startswith("num__"):
            original_feature = feature.split("__", 1)[1]
            X_selected[feature] = X_original[original_feature].to_numpy()

    return X_selected

def select_filter_features(X_train, y_train, X_valid, experiment, preprocessor):
    """
    Fit the existing filter procedure using only the outer training data.
    """

    preprocessor = clone(preprocessor)
    X_train_transformed = preprocessor.fit_transform(X_train)
    X_valid_transformed = preprocessor.transform(X_valid)

    if sparse.issparse(X_train_transformed):
        X_train_transformed = X_train_transformed.toarray()
        X_valid_transformed = X_valid_transformed.toarray()

    if experiment == "Univariate":
        selector = SelectKBest(
            score_func=f_classif,
            k=N_SELECTED_FEATURES
        )
    else:
        selector = MRMRSelector(
            k=N_SELECTED_FEATURES,
            random_state=42
        )

    selector.fit(X_train_transformed, y_train)

    if experiment == "Univariate":
        selected_indices = np.flatnonzero(selector.get_support())
    else:
        selected_indices = selector.get_support()

    selected_feature_names = (
        preprocessor.get_feature_names_out()[selected_indices].tolist()
    )

    X_train_selected = restore_numerical_features(
        X_train_transformed[:, selected_indices],
        X_train,
        selected_feature_names
    )

    X_valid_selected = restore_numerical_features(
        X_valid_transformed[:, selected_indices],
        X_valid,
        selected_feature_names
    )

    return X_train_selected, X_valid_selected, selected_feature_names

def evaluate_subset(X, y, selected_features, inner_splits):
    """
    Estimate the internal F1 of a candidate subset using fresh RIPPER fits.
    """

    scores = []

    for train_indices, valid_indices in inner_splits:

        predictions, classifier = fit_predict(
            X.iloc[train_indices][selected_features],
            y.iloc[train_indices],
            X.iloc[valid_indices][selected_features]
        )

        scores.append(
            f1_score(
                y.iloc[valid_indices],
                predictions,
                zero_division=0
            )
        )

    return float(np.mean(scores))

def select_wrapper_features(X, y):
    """
    Select original predictors using RIPPER and internal cross-validation.
    """

    inner_splits = list(inner_cv.split(X, y))
    selected_features = []
    best_subset = []
    best_score = -np.inf
    selection_trace = []

    for step in range(1, N_WRAPPER_FEATURES + 1):

        candidates = []

        for feature in X.columns:

            if feature in selected_features:
                continue

            candidate_features = selected_features + [feature]

            score = evaluate_subset(
                X,
                y,
                candidate_features,
                inner_splits
            )

            candidates.append((score, feature))

        score, feature = max(candidates, key=lambda item: item[0])
        selected_features.append(feature)

        selection_trace.append({
            "step": step,
            "features": selected_features.copy(),
            "inner_f1": score
        })

        if score > best_score:
            best_score = score
            best_subset = selected_features.copy()

    return best_subset, selection_trace

def calculate_metrics(y_valid, predictions):
    """
    Calculate the same held-out metrics used in the previous experiments.
    """

    return {
        "Accuracy": accuracy_score(y_valid, predictions),
        "Precision": precision_score(y_valid, predictions, zero_division=0),
        "Recall": recall_score(y_valid, predictions, zero_division=0),
        "F1": f1_score(y_valid, predictions, zero_division=0),
        "Balanced Accuracy": balanced_accuracy_score(y_valid, predictions)
    }

def evaluate_ripper(experiment, X, y, cv, preprocessor=None):
    """
    Evaluate RIPPER under one feature strategy using stratified outer folds.
    """

    if experiment not in ["All Features", "Univariate", "Multivariate", "Wrapper"]:
        raise ValueError(f"Unknown experiment: {experiment}")
    if experiment in ["Univariate", "Multivariate"] and preprocessor is None:
        raise ValueError("Filter experiments require an unfitted preprocessor")
    results = []

    for fold, (train_indices, valid_indices) in enumerate(cv.split(X, y), 1):

        X_train = X.iloc[train_indices]
        y_train = y.iloc[train_indices]
        X_valid = X.iloc[valid_indices]
        selection_trace = []

        if experiment == "All Features":
            X_train_selected = X_train
            X_valid_selected = X_valid
            selected_features = X_train.columns.tolist()

        elif experiment in ["Univariate", "Multivariate"]:
            X_train_selected, X_valid_selected, selected_features = (
                select_filter_features(X_train, y_train, X_valid, experiment, preprocessor)
            )

        else:
            selected_features, selection_trace = select_wrapper_features(
                X_train,
                y_train
            )
            X_train_selected = X_train[selected_features]
            X_valid_selected = X_valid[selected_features]

        predictions, classifier = fit_predict(
            X_train_selected,
            y_train,
            X_valid_selected
        )

        result = {
            "Experiment": experiment,
            "Model": "RIPPER",
            "Fold": fold,
            "Number of Features": len(selected_features),
            "Selected Features": json.dumps(selected_features),
            "Wrapper Trace": json.dumps(selection_trace),
            "Rules": str(classifier.ruleset_),
            "Discretization": json.dumps(
                classifier.bin_transformer_.bins_,
                default=str
            )
        }

        result.update(calculate_metrics(y.iloc[valid_indices], predictions))
        results.append(result)

    return results

def summarize_ripper(fold_results):
    """Match cross_validate means and population standard deviations (ddof=0)."""
    result = {"Model": "RIPPER"}
    if fold_results["Experiment"].iloc[0] != "All Features":
        result["Selected Features"] = fold_results["Number of Features"].mean()
    for key, column in {"accuracy": "Accuracy", "precision": "Precision",
                        "recall": "Recall", "f1": "F1",
                        "balanced_accuracy": "Balanced Accuracy"}.items():
        result[f"{key}_mean"] = fold_results[column].mean()
        result[f"{key}_std"] = fold_results[column].std(ddof=0)
    return result


def export_ripper_folds(fold_results, path):
    """Replace only this notebook's strategy in the shared interpretability artifact.

    The standard experiment CSVs are written directly by each notebook; only
    this additional artifact is accumulated across the four notebooks.
    """
    path = Path(path)
    experiments = fold_results["Experiment"].unique()
    if path.exists():
        previous = pd.read_csv(path)
        fold_results = pd.concat([
            previous.loc[~previous["Experiment"].isin(experiments)], fold_results
        ], ignore_index=True)
    order = {name: i for i, name in enumerate(
        ["All Features", "Univariate", "Multivariate", "Wrapper"])}
    fold_results = fold_results.sort_values(
        ["Experiment", "Fold"], key=lambda s: s.map(order) if s.name == "Experiment" else s
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    fold_results.to_csv(path, index=False)
